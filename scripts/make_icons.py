"""Render every glyph file onto the Gruvbox tile.

Usage:  python scripts/make_icons.py
Reads:  glyphs/*.json (validated first; any error stops the run)
Writes: icons/svg/<name>.svg, icons/png/<name>.png (192x192), iconback.svg/png (plain tile),
        preview/icons_sheet.png, editor/library.js (icon library for Icon Studio)
"""
import io
import json
import sys
from pathlib import Path

import resvg_py
from PIL import Image, ImageDraw, ImageFont

import palette
from apps import APPS, FALLBACK
from glyph_store import GLYPH_DIR, SIZE, load_all, svg_for, validate
from palette import BG0_H, FG, GRAY, rgb

ROOT = Path(__file__).resolve().parent.parent
SVG_DIR = ROOT / "icons" / "svg"
PNG_DIR = ROOT / "icons" / "png"
PREVIEW = ROOT / "preview"
EDITOR_LIBRARY = ROOT / "editor" / "library.js"


def render(svg: str) -> Image.Image:
    png = resvg_py.svg_to_bytes(svg_string=svg, width=SIZE, height=SIZE)
    return Image.open(io.BytesIO(bytes(png))).convert("RGBA")


def preview_sheet(names: list[str], cols=8, cell=132, gap_x=36, label_h=40, pad=56):
    rows = -(-len(names) // cols)
    w = pad * 2 + cols * cell + (cols - 1) * gap_x
    h = pad * 2 + rows * (cell + label_h + 24)
    wp = ROOT / "wallpapers" / "gruvbox_clean_a_glow.png"
    bg = (Image.open(wp).convert("RGB").resize((w, int(w * 2392 / 1080))).crop((0, 0, w, h))
          if wp.exists() else Image.new("RGB", (w, h), rgb(BG0_H)))
    if bg.height < h:  # tall sheets: extend with the darkest background
        full = Image.new("RGB", (w, h), rgb(BG0_H))
        full.paste(bg, (0, 0))
        bg = full
    d = ImageDraw.Draw(bg)
    font = ImageFont.load_default(size=18)
    for k, name in enumerate(names):
        r, c = divmod(k, cols)
        x = pad + c * (cell + gap_x)
        y = pad + r * (cell + label_h + 24)
        icon = Image.open(PNG_DIR / f"{name}.png").resize((cell, cell), Image.LANCZOS)
        bg.paste(icon, (x, y), icon)
        label = APPS[name][0] if name in APPS else name
        tw = d.textlength(label, font=font)
        if tw > cell + gap_x - 6:
            label = name
            tw = d.textlength(label, font=font)
        d.text((x + (cell - tw) / 2, y + cell + 10), label,
               fill=rgb(FG if name in APPS else GRAY), font=font)
    return bg


def write_editor_library(glyphs: dict[str, dict]):
    """Icon Studio loads this as a plain <script>, so it also works when opened from disk."""
    colours = {k.lower(): v for k, v in vars(palette).items()
               if k.isupper() and isinstance(v, str) and v.startswith("#")}
    EDITOR_LIBRARY.parent.mkdir(exist_ok=True)
    EDITOR_LIBRARY.write_text(
        "// Generated by scripts/make_icons.py. Do not edit.\n"
        f"window.ICON_LIBRARY = {json.dumps(list(glyphs.values()), separators=(',', ':'))};\n"
        f"window.GRUVBOX = {json.dumps(colours)};\n",
        encoding="utf-8", newline="\n")


def main():
    glyphs = load_all()
    failed = False
    for name, g in glyphs.items():
        errors, _ = validate(g, str(GLYPH_DIR / f"{name}.json"))
        for e in errors:
            print(f"glyphs/{name}.json: {e}", file=sys.stderr)
            failed = True
    if failed or FALLBACK not in glyphs:
        raise SystemExit("fix the glyph files above first (or run scripts/validate_icons.py)")

    SVG_DIR.mkdir(parents=True, exist_ok=True)
    PNG_DIR.mkdir(parents=True, exist_ok=True)
    keep = set(glyphs) | {"iconback"}
    for stale in [*SVG_DIR.glob("*.svg"), *PNG_DIR.glob("*.png")]:
        if stale.stem not in keep:  # icon removed or renamed
            stale.unlink()

    for name in [*glyphs, "iconback"]:
        svg = svg_for(glyphs.get(name))
        (SVG_DIR / f"{name}.svg").write_text(svg, encoding="utf-8", newline="\n")
        render(svg).save(PNG_DIR / f"{name}.png", optimize=True)
    print(f"wrote {len(glyphs) + 1} icons to {SVG_DIR} and {PNG_DIR}")

    PREVIEW.mkdir(exist_ok=True)
    names = [n for n in glyphs if n != FALLBACK] + [FALLBACK]
    preview_sheet(names).save(PREVIEW / "icons_sheet.png", optimize=True)
    print("wrote", PREVIEW / "icons_sheet.png")
    write_editor_library(glyphs)
    print("wrote", EDITOR_LIBRARY)


if __name__ == "__main__":
    main()
